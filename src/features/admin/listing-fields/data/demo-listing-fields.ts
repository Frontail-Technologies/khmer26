export function getAssignedFieldsForCategory(categoryId: string): {
  assignment: CategoryFieldAssignment
  field: ListingField
}[] {
  const assignments = DEMO_CATEGORY_FIELD_ASSIGNMENTS.filter(
    (a) => a.categoryId === categoryId
  ).sort((a, b) => a.sortOrder - b.sortOrder)

  return assignments
    .map((assignment) => {
      const field = DEMO_LISTING_FIELDS.find((f) => f.id === assignment.fieldId)
      if (!field) return null
      return { assignment, field }
    })
    .filter((item): item is { assignment: CategoryFieldAssignment; field: ListingField } => item !== null)
}
